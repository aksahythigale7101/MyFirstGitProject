def SQUAREPATTERN():
    for i in range(1, 5):
        for j in range(1, 5):
            print("*", end=" ")

        print()

#-----------------------------------

def RIGHTTRAINGLE():
    for i  in range(1,5):
        for j in range(i):
            print("*", end=" ")

        print()


# --------------------------------------
def INVERTEDTRAINGLE():
    for i in range(5,0,-1):
        for j in range(i):
            print("*", end=" ")

        print()#comment

